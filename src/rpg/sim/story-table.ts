function column(pick: (r: StoryRow) => number): Int16Array {
  const out = new Int16Array(STORY_ROWS.length)
  for (let i = 0; i < STORY_ROWS.length; i++) out[i] = pick(STORY_ROWS[i]!)
  return out
}

