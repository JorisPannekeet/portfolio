  'BREN_CHEST',
  'VAL_SALT_ROCKS', 'VAL_SHRINE0_ROCKS', 'VAL_SHRINE2_BARRICADE', 'VAL_VELLIN_GATE', 'VAL_VELLIN_SWITCH', 'VAL_SEAL',
  'VAL_CHEST_EAST', 'VAL_CHEST_SOUTH',
  'BARROW_KEY', 'BARROW_DOOR', 'BARROW_ITEM_CHEST', 'BARROW_ALCOVE_CHEST', 'BARROW_VAULT_CHEST', 'BARROW_CORRUPT_CHEST', 'BARROW_B1',
  'SALT_KEY', 'SALT_DOOR', 'SALT_ITEM_CHEST', 'SALT_ALCOVE_CHEST', 'SALT_VAULT_CHEST', 'SALT_CORRUPT_CHEST', 'SALT_P1',
