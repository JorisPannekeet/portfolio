  'BOSS_BARROW', 'BOSS_SALTREACH', 'BOSS_ASHFORGE', 'BOSS_VELLIN', 'BOSS_VAREK', 'BOSS_BARROW_CORRUPT', 'BOSS_SALTREACH_CORRUPT',
